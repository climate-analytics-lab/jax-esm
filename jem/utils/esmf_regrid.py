"""JAX-compatible interpolator using ESMF regridding weights.

This module provides a JAX-friendly interface to apply pre-computed
ESMF regridding weights from netCDF files generated by ESMF_regridweightgen.

Grid shapes and the flat arrays used here follow the SCRIP/ESMF convention
directly: `grid_dims = [n_lon, n_lat]` (longitude varies fastest in the
flat storage, Fortran order), so shapes and reshapes throughout this module
are `(n_lon, n_lat)` with `order='F'` -- matching JEM's `SlabGrid`
convention (`jem/components/slab/grid.py`) with no transpose needed.
"""

from dataclasses import dataclass
from functools import partial
from typing import cast

import jax
import jax.numpy as jnp
import numpy as np
import xarray as xr
from jax import jit


@dataclass
class ESMFWeights:
    """Container for ESMF sparse regridding weights.
    
    ESMF stores weights as a sparse matrix in COO (coordinate) format.
    We store these in a JAX-friendly format for efficient computation.
    """

    # Sparse matrix data (COO format)
    row_indices: jnp.ndarray  # Target grid indices
    col_indices: jnp.ndarray  # Source grid indices
    weights: jnp.ndarray      # Interpolation weights
    
    # Grid dimensions
    src_shape: tuple[int, ...]
    dst_shape: tuple[int, ...]
    
    # Optional mask information
    src_mask: jnp.ndarray | None = None
    dst_mask: jnp.ndarray | None = None
    
    # Metadata
    method: str = "unknown"
    src_grid_dims: tuple[str, ...] | None = None
    dst_grid_dims: tuple[str, ...] | None = None
    
    @property
    def n_weights(self) -> int:
        """Number of non-zero weights."""
        return len(self.weights)
    
    @property
    def src_size(self) -> int:
        """Total size of source grid."""
        return int(np.prod(self.src_shape))
    
    @property
    def dst_size(self) -> int:
        """Total size of destination grid."""
        return int(np.prod(self.dst_shape))


class ESMFRegridder:
    """JAX-compatible regridder using ESMF weights.

    This class reads ESMF weight files and provides JIT-compiled
    interpolation functions that work seamlessly in JAX programs.

    Input/output arrays are `(n_lon, n_lat)`, matching `grid_dims` and
    JEM's `SlabGrid` convention directly (Fortran/ESMF order, `order='F'`
    reshape) -- no transpose needed for JEM callers.
    """
    
    def __init__(self,
        weight_file: str,
        src_shape: tuple[int, ...] | None = None,
        dst_shape: tuple[int, ...] | None = None,
    ):
        """Initialize regridder from ESMF weight file.

        ESMF weight files (from ESMF_RegridWeightGen) already carry the
        source/destination grid shapes as `src_grid_dims`/`dst_grid_dims`
        variables (not just n_a/n_b flat sizes), since they're built
        directly from the SCRIP grid files -- so src_shape/dst_shape don't
        need to be supplied by the caller; they're read from the weight
        file itself when not given. The parameters remain as an
        override/validation check for weight files that don't carry this
        metadata.

        Parameters
        ----------
        weight_file : str
            Path to netCDF file generated by ESMF_regridweightgen
        src_shape : tuple of int, optional
            Shape of source grid (n_lon, n_lat). If None, read from the
            weight file's own src_grid_dims variable.
        dst_shape : tuple of int, optional
            Shape of destination grid (n_lon, n_lat). If None, read from
            the weight file's own dst_grid_dims variable.

        """
        self.weight_file = weight_file

        # Load weights (also resolves src_shape/dst_shape if not supplied)
        self.weights = self._load_weights(src_shape, dst_shape)
        self.src_shape = self.weights.src_shape
        self.dst_shape = self.weights.dst_shape

        # Create JIT-compiled interpolation function
        self._interp_fn = jit(self._interpolate_impl)

    def _load_weights(
        self,
        src_shape: tuple[int, ...] | None,
        dst_shape: tuple[int, ...] | None,
    ) -> ESMFWeights:
        """Load ESMF weights from netCDF file using xarray.

        ESMF weight files contain:
        - S: sparse weight matrix values
        - col: source (column) indices (1-based in file)
        - row: destination (row) indices (1-based in file)

        `col`/`row` index into src/dst data flattened in SCRIP's native
        Fortran order (the first `grid_dims` axis -- longitude -- varies
        fastest); `grid_dims = [n_lon, n_lat]` already gives this
        regridder's `(n_lon, n_lat)` shape directly, so `order='F'`
        recovers the correct field with no transpose needed.
        `_interpolate_impl` reshapes accordingly.
        """
        # Open dataset with xarray
        ds = xr.open_dataset(self.weight_file)

        try:
            # Read sparse matrix data
            # ESMF uses 1-based indexing, convert to 0-based
            col_indices = ds['col'].values - 1
            row_indices = ds['row'].values - 1
            weights = ds['S'].values

            # Read metadata if available
            method = ds.attrs.get('map_method', 'unknown')

            # Read grid sizes to validate
            src_grid_size = ds.sizes['n_a']
            dst_grid_size = ds.sizes['n_b']

            # Infer src_shape/dst_shape from the weight file's own
            # src_grid_dims/dst_grid_dims variables when not supplied.
            # Those variables are already (n_lon, n_lat), matching this
            # class's convention directly.
            if src_shape is None:
                if 'src_grid_dims' not in ds.variables:
                    raise ValueError(
                        f"'{self.weight_file}' has no src_grid_dims variable and "
                        "no src_shape was supplied -- cannot determine source grid shape."
                    )
                src_shape = tuple(int(n) for n in ds['src_grid_dims'].values)
            if dst_shape is None:
                if 'dst_grid_dims' not in ds.variables:
                    raise ValueError(
                        f"'{self.weight_file}' has no dst_grid_dims variable and "
                        "no dst_shape was supplied -- cannot determine destination grid shape."
                    )
                dst_shape = tuple(int(n) for n in ds['dst_grid_dims'].values)

            # Validate dimensions
            expected_src_size = int(np.prod(src_shape))
            expected_dst_size = int(np.prod(dst_shape))

            if src_grid_size != expected_src_size:
                raise ValueError(
                    f"Source grid size mismatch: file has {src_grid_size}, "
                    f"expected {expected_src_size} from shape {src_shape}"
                )

            if dst_grid_size != expected_dst_size:
                raise ValueError(
                    f"Destination grid size mismatch: file has {dst_grid_size}, "
                    f"expected {expected_dst_size} from shape {dst_shape}"
                )

            # Read masks if available
            src_mask = None
            dst_mask = None

            if 'mask_a' in ds.variables:
                src_mask_flat = ds['mask_a'].values
                src_mask = jnp.array(
                    np.asarray(src_mask_flat).reshape(src_shape, order='F')
                )

            if 'mask_b' in ds.variables:
                dst_mask_flat = ds['mask_b'].values
                dst_mask = jnp.array(
                    np.asarray(dst_mask_flat).reshape(dst_shape, order='F')
                )
            
            # Try to extract grid dimension names if available
            src_grid_dims = None
            dst_grid_dims = None
            
            if 'src_grid_dims' in ds.attrs:
                src_grid_dims = tuple(ds.attrs['src_grid_dims'].split(','))
            if 'dst_grid_dims' in ds.attrs:
                dst_grid_dims = tuple(ds.attrs['dst_grid_dims'].split(','))
        
        finally:
            ds.close()
        
        # Convert to JAX arrays. The weights take the working precision of the
        # process: float64 under `jax_enable_x64`, so a float64 field is not
        # mapped through float32 weights (which would put ~1e-8 of error into
        # every row sum), and float32 otherwise, which is all JAX holds.
        # `config.read`, not attribute access: the attribute is not declared
        # on jax's `Config` in every supported jax release, and mypy is a gate.
        weight_dtype = (
            jnp.float64 if jax.config.read("jax_enable_x64") else jnp.float32
        )
        return ESMFWeights(
            row_indices=jnp.array(row_indices, dtype=jnp.int32),
            col_indices=jnp.array(col_indices, dtype=jnp.int32),
            weights=jnp.array(weights, dtype=weight_dtype),
            src_shape=src_shape,
            dst_shape=dst_shape,
            src_mask=src_mask,
            dst_mask=dst_mask,
            method=method,
            src_grid_dims=src_grid_dims,
            dst_grid_dims=dst_grid_dims
        )
    
    @partial(jit, static_argnums=(0,))
    def _interpolate_impl(self, src_data: jnp.ndarray) -> jnp.ndarray:
        """Core interpolation implementation (JIT-compiled).
        
        Applies sparse matrix multiplication: dst = W @ src
        where W is the sparse weight matrix.

        `col`/`row` index into src/dst flattened in Fortran order (see
        `_load_weights`), so the flatten/reshape here must use order='F' to
        stay aligned with those indices.
        """
        # Flatten source data (Fortran order -- see docstring)
        src_flat = src_data.reshape(-1, order='F')

        # Apply sparse matrix multiplication using scatter-add
        # This is equivalent to: dst[row] += weight * src[col]
        dst_flat = jnp.zeros(self.weights.dst_size, dtype=src_data.dtype)

        # Gather source values and multiply by weights
        src_values = src_flat[self.weights.col_indices]
        # Cast back to the field's dtype: the weights may be float64 (see
        # `_load_weights`) while a component's field is float32, and a
        # scatter-add of a wider dtype into a narrower buffer is not defined.
        weighted_values = (src_values * self.weights.weights).astype(src_data.dtype)

        # Scatter-add to destination
        dst_flat = dst_flat.at[self.weights.row_indices].add(weighted_values)

        # Reshape to destination grid (Fortran order -- see docstring)
        return dst_flat.reshape(self.weights.dst_shape, order='F')
    
    def __call__(self, src_data: jnp.ndarray) -> jnp.ndarray:
        """Interpolate data from source grid to destination grid.
        
        Parameters
        ----------
        src_data : jnp.ndarray
            Data on source grid with shape matching src_shape
            
        Returns
        -------
        jnp.ndarray
            Interpolated data on destination grid

        Raises
        ------
        ValueError
            If ``src_data.shape`` is not ``src_shape``.

        """
        # Shapes are static under `jit`, so this check costs nothing per call
        # and cannot be skipped. It has to be explicit: a transposed
        # (n_lat, n_lon) field has the right number of elements, and a
        # too-small one is gathered from with an out-of-range index that JAX
        # clamps, so neither would raise on its own -- both would return wrong
        # numbers on the destination grid.
        if tuple(src_data.shape) != tuple(self.src_shape):
            raise ValueError(
                f"ESMFRegridder('{self.weight_file}') expects a source field of "
                f"shape (n_lon, n_lat) = {tuple(self.src_shape)}, got "
                f"{tuple(src_data.shape)}."
            )

        return cast(jnp.ndarray, self._interp_fn(src_data))
